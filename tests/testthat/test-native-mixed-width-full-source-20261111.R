# Deterministic descriptive source contract: compare conditional covariance
# versus full-refit functional mixed-effects bootstrap simultaneous band widths.
# Frozen Python eyetrajectoriespy==1.2.0 at
# c1cd95ad718327550f7e55393ff38582872f7a94.
# No bootstrap draws, fitting, model ranking or variance selection here.

.etr_source_mixed_width_fixture <- function(zero_fixed=FALSE) {
  fit<-list(time=c(0,.25,.5,1),
    coefficient_names=c("Intercept","dose","group"),
    coefficient_functions=rbind(c(.3,.4,.45,.6),
      c(-.1,.1,.15,.3),c(.05,.0,.1,.2)))
  center<-rbind(c(.25,.35,.40,.55),
    c(-.05,.05,.1,.25),c(.02,-.03,.07,.17))
  scale<-rbind(c(.1,.15,.12,.2),c(.15,.12,.2,.1),
    c(.08,.15,.1,.12))
  offsets<-c(-.6,-.3,0,.25,.65)
  draws<-array(0,c(5L,3L,4L))
  for(b in seq_along(offsets))
    draws[b,,]<-center+offsets[b]*scale
  fixed<-list(reference=fit,bootstrap_mean=center,
    bootstrap_coefficient_functions=if(zero_fixed)
      array(rep(as.vector(center),each=5L),dim=c(5L,3L,4L))
      else draws,
    bootstrap_standard_errors=scale,
    bootstrap_type="conditional_covariance",
    provenance=list(study="mixed-width-same-reference"))
  # Keep fixed arrays generated by slicing a timewise matrix, not by
  # relying on R's column-major recycling of a B-by-coefficient-by-time array.
  if(zero_fixed)for(b in seq_len(5L))
    fixed$bootstrap_coefficient_functions[b,,]<-center
  full<-list(reference=fit,bootstrap_mean=center,
    bootstrap_coefficient_functions=draws,
    bootstrap_standard_errors=scale*1.4,
    bootstrap_type="full_refit",
    provenance=list(study="mixed-width-same-reference"))
  list(fixed=fixed,full=full)
}

test_that("source comparison preserves complete coefficient/time table and family calibration",{
  for(zero_fixed in c(FALSE,TRUE)){
    f<-.etr_source_mixed_width_fixture(zero_fixed)
    for(scope in c("coefficient","family")){
      x<-etr_compare_functional_mixed_effects_bootstraps(
        f$fixed,f$full,confidence_level=.75,
        simultaneous_scope=scope)
      expect_s3_class(x,"data.frame")
      expect_identical(names(x),c("coefficient","time",
        "fixed_covariance_band_width","full_refit_band_width",
        "full_refit_to_fixed_covariance_width_ratio",
        "confidence_level","simultaneous_scope"))
      expect_identical(nrow(x),12L)
      expect_identical(x$coefficient,rep(
        c("Intercept","dose","group"),each=4L))
      expect_equal(x$time,rep(c(0,.25,.5,1),3L),tolerance=0)
      expect_identical(unique(x$simultaneous_scope),scope)
      expect_true(all(x$confidence_level==.75))
      expect_true(all(x$fixed_covariance_band_width>=0))
      expect_true(all(x$full_refit_band_width>=0))
      if(zero_fixed){
        expect_true(all(x$fixed_covariance_band_width==0))
        expect_true(all(is.infinite(x$full_refit_to_fixed_covariance_width_ratio)))
      }else {
        expect_true(all(x$fixed_covariance_band_width>0))
        expect_equal(x$full_refit_to_fixed_covariance_width_ratio,
          x$full_refit_band_width/x$fixed_covariance_band_width,
          tolerance=2e-12)
      }
    }
  }
})

test_that("source mixed comparison rejects incompatible bootstrap schemas",{
  f<-.etr_source_mixed_width_fixture()
  bad<-f$full
  bad$reference$time[1L]<--1
  expect_error(etr_compare_functional_mixed_effects_bootstraps(f$fixed,bad),
    "both bootstrap objects must share the exact reference fit")
  bad<-f$full
  bad$bootstrap_type<-"conditional_covariance"
  expect_error(etr_compare_functional_mixed_effects_bootstraps(f$fixed,bad),
    "full-refit")
  bad<-f$fixed
  bad$bootstrap_type<-"full_refit"
  expect_error(etr_compare_functional_mixed_effects_bootstraps(bad,f$full),
    "fixed_covariance_bootstrap")
  expect_error(etr_compare_functional_mixed_effects_bootstraps(
    f$fixed,f$full,simultaneous_scope="profile"),
    "simultaneous_scope")
  expect_error(etr_compare_functional_mixed_effects_bootstraps(
    f$fixed,f$full,confidence_level=0),"confidence_level")
})

test_that("full frozen Python 1.2 typed shared-reference comparison is cell-identical",{
  if(!identical(Sys.getenv("ET_RUN_PYTHON_TESTS"),"true"))
    skip("frozen Python 1.2 typed mixed bootstrap comparison opt-in")
  expect_identical(et_python_version(),"1.2.0")
  reticulate::py_run_string("
import numpy as np
import eyetrajectoriespy as et
def _width_obj(cls,**values):
    a=object.__new__(cls)
    for k,v in values.items(): object.__setattr__(a,k,v)
    return a
_w_time=np.array([0.,.25,.5,1.])
_w_fit=_width_obj(et.FunctionalMixedEffectsResult,
    time=_w_time,coefficient_names=('Intercept','dose','group'),
    coefficient_functions=np.array([
        [.3,.4,.45,.6],[-.1,.1,.15,.3],[.05,0.,.1,.2]]))
_w_center=np.array([
    [.25,.35,.40,.55],[-.05,.05,.1,.25],[.02,-.03,.07,.17]])
_w_scale=np.array([
    [.1,.15,.12,.2],[.15,.12,.2,.1],[.08,.15,.1,.12]])
_w_offsets=np.array([-.6,-.3,0.,.25,.65])
_w_draws=np.stack([_w_center+o*_w_scale for o in _w_offsets])
_w_results={}
for _zero in (False,True):
    _f=_width_obj(et.FunctionalMixedEffectsBootstrapResult,
      reference=_w_fit,bootstrap_mean=_w_center,
      bootstrap_coefficient_functions=(
        np.repeat(_w_center[None,:,:],5,axis=0) if _zero else _w_draws),
      bootstrap_standard_errors=_w_scale,
      provenance={'study':'mixed-width-same-reference'})
    _r=_width_obj(et.FunctionalMixedEffectsFullRefitBootstrapResult,
      reference=_w_fit,bootstrap_mean=_w_center,
      bootstrap_coefficient_functions=_w_draws,
      bootstrap_standard_errors=_w_scale*1.4,
      provenance={'study':'mixed-width-same-reference'})
    for _scope in ('coefficient','family'):
       _w_results[(_zero,_scope)]=et.compare_functional_mixed_effects_bootstraps(
           _f,_r,confidence_level=.75,simultaneous_scope=_scope)
")
  for(zero_fixed in c(FALSE,TRUE)){
    f<-.etr_source_mixed_width_fixture(zero_fixed)
    for(scope in c("coefficient","family")){
      actual<-etr_compare_functional_mixed_effects_bootstraps(
        f$fixed,f$full,confidence_level=.75,simultaneous_scope=scope)
      result<-reticulate::py_eval(paste0("_w_results[(",
        if(zero_fixed)"True" else "False",",'",scope,"')]"),
        convert=FALSE)
      expected<-et_to_r(result)
      expect_identical(names(actual),names(expected))
      expect_identical(as.character(actual$coefficient),
        as.character(expected$coefficient))
      expect_identical(as.character(actual$simultaneous_scope),
        as.character(expected$simultaneous_scope))
      for(field in setdiff(names(actual),c("coefficient",
          "simultaneous_scope")))
        expect_equal(actual[[field]],expected[[field]],
          tolerance=3e-12,ignore_attr=TRUE,
          info=paste("source width",zero_fixed,scope,field))
    }
  }
})
