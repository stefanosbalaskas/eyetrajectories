# FLAGSHIP 01 — Complete dense gaze-trajectory analysis (SYNTHETIC DATA ONLY)
# Tested against published eyetrajectories v0.4.3; no Python required.
# Run: source("inst/examples/flagship/01_complete_gaze_trajectory.R")
# Output: ET_FLAGSHIP_OUTPUT or artifacts/flagship-workflows/01-dense.
stopifnot(requireNamespace("eyetrajectories",quietly=TRUE))
suppressPackageStartupMessages(library(eyetrajectories))
set.seed(20261118L)
n <- 48L; nt <- 61L; t <- seq(0,1,length.out=nt)
participants <- rep(seq_len(24L),each=2L)
condition <- rep(c("A","B"),times=24L)
vals <- array(0,c(n,nt,2L))
subject_u <- stats::rnorm(24L,sd=.08)
for(i in seq_len(n)) {
  phase <- if(condition[i]=="B") .12 else 0
  vals[i,,1] <- .5 + .25*sin(2*pi*(t+phase)) +
    subject_u[participants[i]] + stats::rnorm(nt,sd=.014)
  vals[i,,2] <- .5 + .20*cos(2*pi*(t+phase)) +
    .65*subject_u[participants[i]] + stats::rnorm(nt,sd=.014)
}
ids<-sprintf("synthetic_trial_%03d",seq_len(n))
x <- etr_trajectory_set(t,vals,curve_ids=ids,
  dimension_names=c("horizontal_screen_fraction","vertical_screen_fraction"),
  coordinate_system="normalized_screen",time_unit="within_trial_normalized")
stopifnot(isTRUE(etr_validate(x,require_complete=TRUE)))
d <- etr_pairwise_l2(x)
stopifnot(all(is.finite(d)),max(abs(d-t(d)))<1e-10,all(diag(d)==0))
fit <- etr_fit_mfpca(x,n_components=2L)
score <- etr_fpca_scores(fit)
var <- etr_fpca_variance_frame(fit)
rec <- etr_reconstruct_fpca(fit,n_components=2L)
rmse <- sqrt(mean((rec$values-x$values)^2))
stopifnot(all(is.finite(score$FPC1)),all(is.finite(var$variance_ratio)),
          is.finite(rmse),is.finite(sum(var$variance_ratio)))
root <- Sys.getenv("ET_FLAGSHIP_OUTPUT",file.path("artifacts","flagship-workflows"))
out <- file.path(root,"01-dense"); dir.create(out,recursive=TRUE,showWarnings=FALSE)
utils::write.csv(data.frame(curve_id=ids,participant=participants,
   condition=condition),file.path(out,"synthetic_design.csv"),row.names=FALSE)
utils::write.csv(score,file.path(out,"fpca_scores.csv"),row.names=FALSE)
utils::write.csv(var,file.path(out,"fpca_variance.csv"),row.names=FALSE)
utils::write.csv(data.frame(metric=c("n_curves","n_participants","grid_points",
  "dimension_count","reconstruction_rmse"),
  value=c(n,24,nt,2,rmse)),file.path(out,"results.csv"),row.names=FALSE)
grDevices::pdf(file.path(out,"01_planar_trajectories.pdf"),width=7,height=5)
etr_plot_trajectories(x,max_curves=24L)
grDevices::dev.off()
grDevices::pdf(file.path(out,"02_fpca_variance.pdf"),width=7,height=5)
etr_plot_fpca_variance(fit)
grDevices::dev.off()
grDevices::pdf(file.path(out,"03_component_scores.pdf"),width=7,height=5)
graphics::plot(score$FPC1,score$FPC2,
  pch=ifelse(condition=="A",16,1),col="steelblue",
  xlab="FPC1 score",ylab="FPC2 score",
  main="Synthetic common-grid MFPCA scores")
graphics::legend("topright",legend=c("Condition A","Condition B"),
   pch=c(16,1),col="steelblue",bty="n")
grDevices::dev.off()
writeLines(c("# Workflow 01 — Synthetic dense gaze trajectories","",
 "Design: 24 simulated participants × 2 conditions = 48 trajectories; 61 aligned samples.",
 "Coordinates: normalized screen position, NOT measured pixels or degrees.",
 "Time: synthetic within-trial normalized 0–1; no interpolation, sample loss or data cleaning applied.",
 "Methods: native R etr_trajectory_set, etr_pairwise_l2, etr_fit_mfpca, etr_reconstruct_fpca.",
 sprintf("Two-component reconstruction RMSE: %.8f (descriptive, same training data)",rmse),
 "FPCA is descriptive; no causal difference or statistical significance is claimed.",
 "Data are generated by the script and are NOT human eye-tracking observations.",
 "For real data declare calibration, device, sample rate, AOIs, source version, missingness and alignment."),
 file.path(out,"METHODS_AND_LIMITATIONS.md"))
writeLines(capture.output(utils::sessionInfo()),file.path(out,"sessionInfo.txt"))
stopifnot(length(list.files(out,pattern="\\.pdf$"))==3L)
cat("FLAGSHIP_01_DENSE_SYNTHETIC_PASS=",normalizePath(out),"\n",sep="")
